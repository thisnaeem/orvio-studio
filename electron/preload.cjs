const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('studio',Object.freeze({
 platform:process.platform,
 minimize:()=>ipcRenderer.invoke('window:minimize'),
 maximize:()=>ipcRenderer.invoke('window:maximize'),
 closeWindow:()=>ipcRenderer.invoke('window:close'),
 saveMedia:input=>ipcRenderer.invoke('media:save',input),
 chooseMedia:accountId=>ipcRenderer.invoke('media:choose',accountId),
 listModels:input=>ipcRenderer.invoke('ai:models',input),
 connectDrive:input=>ipcRenderer.invoke('drive:connect',input),
 disconnectDrive:()=>ipcRenderer.invoke('drive:disconnect'),
 listDriveFiles:()=>ipcRenderer.invoke('drive:files'),
 uploadDriveFile:()=>ipcRenderer.invoke('drive:upload'),
 chat:input=>ipcRenderer.invoke('ai:chat',input),
 connectMeta:input=>ipcRenderer.invoke('meta:connect',input),
 disconnectMeta:id=>ipcRenderer.invoke('meta:disconnect',id),
 getWorkspace:()=>ipcRenderer.invoke('workspace:state'),
 schedule:input=>ipcRenderer.invoke('jobs:schedule',input),
 cancelJob:id=>ipcRenderer.invoke('jobs:cancel',id),
 savePreferences:input=>ipcRenderer.invoke('workspace:preferences',input),
 saveAI:input=>ipcRenderer.invoke('ai:save',input),
 generateCaption:prompt=>ipcRenderer.invoke('ai:generate',prompt),
 onWorkspace:callback=>{const listener=(_event,state)=>callback(state);ipcRenderer.on('workspace:changed',listener);return()=>ipcRenderer.removeListener('workspace:changed',listener);},
 checkUpdates:()=>ipcRenderer.invoke('updates:check'),
 getUpdateState:()=>ipcRenderer.invoke('updates:state'),
 installUpdate:()=>ipcRenderer.invoke('updates:install'),
 openReleases:()=>ipcRenderer.invoke('updates:releases'),
 getVersion:()=>ipcRenderer.invoke('app:version'),
 onUpdate:callback=>{const listener=(_event,state)=>callback(state);ipcRenderer.on('update:status',listener);return()=>ipcRenderer.removeListener('update:status',listener);}
}));
